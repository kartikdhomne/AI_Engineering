# ==========================================
# TYPE CONVERSION
# ==========================================

# Integer

num = 10

print(float(num))
print(str(num))
print(bool(num))

# Float

price = 99.99

print(int(price))
print(str(price))

# String

number = "100"

print(int(number))
print(float(number))

# Boolean

print(int(True))
print(int(False))

print(str(True))

