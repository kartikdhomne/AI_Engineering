# ==========================================
# DATA TYPES
# ==========================================

# Python has many built-in data types.

# Integer

age = 25

# Float

price = 99.99

# String

name = "Python"

# Boolean

is_online = True

# Complex

number = 3 + 5j

# List

fruits = ["Apple", "Banana", "Orange"]

# Tuple

coordinates = (10, 20)

# Set

colors = {"Red", "Green", "Blue"}

# Dictionary

student = {
    "name": "John",
    "age": 21
}

# None

data = None

print(type(age))
print(type(price))
print(type(name))
print(type(is_online))
print(type(number))
print(type(fruits))
print(type(coordinates))
print(type(colors))
print(type(student))
print(type(data))