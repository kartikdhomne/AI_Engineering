# ==========================================
# USER INPUT
# ==========================================

# input() always returns a string.

name = input("Enter your name: ")

print("Hello", name)

# Convert input into integer.

age = int(input("Enter age: "))

print(age)

# Float input

salary = float(input("Enter salary: "))

print(salary)

# Boolean conversion

value = bool(input("Enter something: "))

print(value)