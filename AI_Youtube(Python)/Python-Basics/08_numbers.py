a = 10
b = 3

print(a + b)
print(a - b)
print(a * b)
print(a / b)

# Integer division

print(a // b)

# Modulus

print(a % b)

# Power

print(a ** b)

# Absolute value

print(abs(-100))

# Round

print(round(4.67))

# Maximum

print(max(10, 20, 30))

# Minimum

print(min(10, 20, 30))