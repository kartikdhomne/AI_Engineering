# ==========================================
# VARIABLES
# ==========================================

# A variable stores data.

name = "Kartik"
age = 25
salary = 50000

print(name)
print(age)
print(salary)

# Variables can be reassigned.

age = 26
print(age)

# Multiple assignment

x, y, z = 10, 20, 30

print(x)
print(y)
print(z)

# Same value to multiple variables

a = b = c = 100

print(a)
print(b)
print(c)

# Variable naming rules

first_name = "John"
_last_name = "Doe"

print(first_name)
print(_last_name)

# Invalid variable names

# 1name = "ABC"
# first-name = "ABC"
# class = "Python"

# Python is dynamically typed.

number = 10
print(number)

number = "Ten"
print(number)